def version_label(value):
    if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_-]{0,47}', value):
        raise c.ControllerError('Use a version label such as V4 or V3-risk-r1')
    return value


def copy_content(source, destination):
    """Copy content only, including across WSL/Windows without chmod/copystat."""
    destination.mkdir(parents=True, exist_ok=False)
    for item in sorted(source.rglob('*')):
        relative = item.relative_to(source)
        c.checked_member(relative.as_posix())
        if item.is_symlink(): raise c.ControllerError('Catalog submissions cannot contain symlinks')
        output = destination / relative
        if item.is_dir(): output.mkdir(parents=True, exist_ok=True)
        elif item.is_file():
            output.parent.mkdir(parents=True, exist_ok=True)
            with output.open('xb') as handle: handle.write(item.read_bytes())


def refresh(root):
    versions = []
    table = ['# Solutions and results', '',
             'Generated by the experiment catalog. Versions are immutable; results never overwrite earlier runs.', '',
             '| Version | Valid runs | Mean score | Worst score | Full careers |',
             '| --- | ---: | ---: | ---: | ---: |']
    rows = []
    for metadata in sorted((root / 'solutions').glob('*/version.json')):
        version = c.read_json(metadata)
        runs = [c.read_json(p) for p in sorted((root/'results'/version['version']).glob('*/summary.json'))]
        valid = [v for v in runs if v['status'] == 'awaiting_analysis']
        scores = [v['quantitative_score'] for v in valid]
        summary = {'version':version['version'],'submission_sha256':version['submission_sha256'],
            'total_runs':len(runs),'valid_runs':len(valid),'mean_score':sum(scores)/len(scores) if scores else None,
            'worst_score':min(scores) if scores else None,'full_careers':sum(v['survival_months']==48 for v in valid)}
        versions.append(summary)
        mean_label=f"{summary['mean_score']:.2f}" if scores else '—'
        worst_label=f"{min(scores):.2f}" if scores else '—'
        table.append(f"| [{version['version']}](solutions/{version['version']}/) | {len(valid)} | "
                     f"{mean_label} | {worst_label} | {summary['full_careers']} |")
        for run in runs:
            rows.append({key:run.get(key) for key in ['version','run_label','status','quantitative_score','survival_months','outcome','total_tokens','reported_api_cost']})
    c.write_json(root/'index.json',{'versions':versions})
    table += ['', 'Read each result report for source/provenance limitations. One run does not establish a winning version.', '',
              'Raw transcripts, credentials, databases, virtual environments and service logs stay local. This catalog exports compact reports only.', '',
              'Register a new archive under a new label; do not replace an existing version. Use V4-initial or V4-r2 for different revisions.', '']
    (root/'README.md').write_text('\n'.join(table),encoding='utf-8')
    stream=io.StringIO(newline=''); writer=csv.DictWriter(stream,lineterminator='\n',fieldnames=['version','run_label','status','quantitative_score','survival_months','outcome','total_tokens','reported_api_cost'])
    writer.writeheader(); writer.writerows(rows)
    (root/'results.csv').write_text(stream.getvalue(),encoding='utf-8',newline='\n')


def register(root, version, source, provenance='local'):
    version=version_label(version); root.mkdir(parents=True,exist_ok=True)
    with c.RunLock(root/'.catalog.lock','register-'+version):
        with tempfile.TemporaryDirectory(prefix='.catalog-stage-',dir=root) as tmp:
            tmp=Path(tmp)
            if source.is_dir():
                c.copy_submission_tree(source,tmp/'extracted')
            else:
                (tmp/'extracted').mkdir(); c.extract_archive(source,tmp/'extracted')
            solution=c.find_submission_root(tmp/'extracted'); c.validate_basic(solution)
            digest=c.submission_digest(solution); dest=root/'solutions'/version
            if dest.exists():
                existing=c.read_json(dest/'version.json')
                if not existing or existing['submission_sha256']!=digest or c.submission_digest(dest/'solution')!=digest:
                    raise c.ControllerError('Version already contains different files; choose a NEW version label')
                return existing
            dest.mkdir(parents=True)
            copy_content(solution,dest/'solution')
            metadata={'version':version,'submission_sha256':digest,'source':provenance,'registered_at':c.now(),
                      'archive_sha256':c.file_digest(source) if source.is_file() else None}
            c.write_json(dest/'version.json',metadata)
            refresh(root)
            return metadata


def import_report(root,version,report_path,snapshot=None,evidence='Historical import; no pre-run snapshot verified'):
    version=version_label(version)
    with c.RunLock(root/'.catalog.lock','result-'+version):
        metadata=c.read_json(root/'solutions'/version/'version.json')
        if not metadata: raise c.ControllerError('Register the solution version first')
        if snapshot is not None and c.submission_digest(snapshot)!=metadata['submission_sha256']:
            raise c.ControllerError('Result snapshot does not match this version; refusing misattribution')
        fingerprint=c.file_digest(report_path)
        base=root/'results'/version
        for p in base.glob('*/summary.json'):
            if c.read_json(p).get('report_sha256')==fingerprint: return c.read_json(p)
        report=c.read_json(report_path); summary=c.summarize_report(report)
        numbers=[int(p.name[len(version)+1:]) for p in base.glob(version+'_*')
                 if p.is_dir() and p.name[len(version)+1:].isdigit()]
        label=f'{version}_{max(numbers,default=0)+1}'
        dest=base/label; dest.mkdir(parents=True)
        usage=summary.get('token_usage',{})
        safe={key:summary.get(key) for key in ['status','quantitative_score','survival_months','completed','outcome','scored_at']}
        safe.update(version=version,run_label=label,submission_sha256=metadata['submission_sha256'],report_sha256=fingerprint,
                    total_tokens=usage.get('total_tokens'),reported_api_cost=usage.get('total_cost'),
                    source_evidence=evidence,provided_snapshot_matches=snapshot is not None)
        c.write_json(dest/'summary.json',safe)
        body=[f'# {label}', '', f"Status: {safe['status']}",f"Score: {safe['quantitative_score']}",
              f"Months: {safe['survival_months']}",f"Outcome: {safe['outcome']}",'',
              'Reported API cost is an estimate supplied by the runner, not a verified provider invoice.', '',
              'Source evidence: '+evidence, '', 'Submission SHA256: '+metadata['submission_sha256'],
              'Report SHA256: '+fingerprint, '']
        (dest/'report.md').write_text('\n'.join(body),encoding='utf-8')
        # Analysis stays local by default; arbitrary log text is not published automatically.
        refresh(root)
        return safe


def import_managed(root,version,run_root):
    run=c.read_json(run_root/'run.json')
    if not run or run.get('status') not in c.TERMINAL | {'awaiting_approval'}:
        raise c.ControllerError('Managed run has not finished')
    snapshot=run_root/'submission'
    if str(snapshot.resolve())!=str(Path(run['submission']).resolve()): raise c.ControllerError('Run snapshot path mismatch')
    report=run_root/'score_report.json'
    if report.exists():
        body=c.read_json(report)
        if body.get('submission_dir')!=run['submission']: raise c.ControllerError('Report belongs to another run snapshot')
    else: report=run_root/'run.json'
    return import_report(root,version,report,snapshot,'Controller frozen pre-run snapshot; run '+run['id'])


def import_batch(root,workspace,batch_id):
    from parallel import batch_path,collect_summary
    folder=batch_path(workspace,batch_id);batch=c.read_json(folder/'batch.json')
    if not batch or batch['status'] not in {'awaiting_analysis','partial_failure','interrupted'}:
        raise c.ControllerError('Batch has not finished')
    imported=[]
    for worker in batch['workers']:
        state=Path(worker['workspace'])/'.experiments';status=c.read_json(state/'status.json',{})
        if status.get('id'):imported.append(import_managed(root,batch['version'],state/'runs'/status['id']))
    summary=collect_summary(batch)
    # Deliberately export only public metrics, not local paths/session IDs or logs.
    safe={'batch_id':batch_id,'version':batch['version'],'status':batch['status'],
          'submission_sha256':batch['submission_sha256'],'expected_runs':summary['expected_runs'],
          'valid_runs':summary['valid_runs'],'mean_score':summary['mean_score'],
          'worst_score':summary['worst_score'],'full_careers':summary['full_careers'],
          'runs':[{k:v.get(k) for k in ('label','status','quantitative_score','survival_months','outcome')} for v in summary['runs']]}
    c.write_json(root/'batches'/batch_id/'summary.json',safe)
    return {'batch':safe,'imported':imported}


